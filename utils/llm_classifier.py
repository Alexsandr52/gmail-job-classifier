def classify(subject, body):

    prompt = f"""
ТЕМА:
{subject or ""}

ПИСЬМО:
{body or ""}
""".strip()

    payload = {
        "model": MODEL_NAME,
        "messages": [
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": prompt,
            },
        ],
        "stream": False,
        # Qwen3 умеет thinking,
        # но для такой классификации он нам не нужен.
        "think": False,
        # Ollama заставляет модель
        # вернуть JSON по нашей схеме.
        "format": SCHEMA,
        "options": {
            "temperature": 0,
            "num_predict": 32,
        },
        "keep_alive": KEEP_ALIVE,
    }

    response = requests.post(
        OLLAMA_URL,
        json=payload,
        timeout=120,
    )

    response.raise_for_status()

    data = response.json()

    result = json.loads(data["message"]["content"])

    return result["category"]


def unload_model():
    """
    Выгружает модель из RAM.

    С диска она НЕ удаляется.
    """

    requests.post(
        OLLAMA_URL,
        json={
            "model": MODEL_NAME,
            "messages": [],
            "stream": False,
            "keep_alive": 0,
        },
        timeout=30,
    )


